const test = require('node:test');
const assert = require('node:assert/strict');
const {
    isExcludedPath, isNoisePath, looksGeneratedContent, setExtraExcludedDirs
} = require('../out/pathRules');

test('node_modules e saídas de build nunca entram no contexto', () => {
    for (const p of [
        'node_modules/x/index.js',
        'apps/web/node_modules/react/index.js',
        'dist/a.js', 'build/a.js', '.next/server/a.js', 'out/a.js',
        'web/.output/server/index.mjs', 'apps/api/.turbo/log.txt'
    ]) assert.equal(isExcludedPath(p), true, p);
});

test('Prisma: client gerado fica de fora, schema e migrations ficam', () => {
    for (const p of [
        'node_modules/.prisma/client/index.js',
        'node_modules/@prisma/client/index.d.ts',
        'src/generated/prisma/index.js',
        'generated/prisma/client.ts',
        'prisma/generated/zod/index.ts',
        'apps/api/.prisma/client/index.js'
    ]) assert.equal(isExcludedPath(p), true, p);

    for (const p of [
        'prisma/schema.prisma',
        'prisma/migrations/20240101_init/migration.sql',
        'prisma/seed.ts',
        'src/lib/prisma.ts'
    ]) assert.equal(isExcludedPath(p), false, p);
});

test('lockfiles, mapas e minificados são ruído; package.json não', () => {
    for (const p of ['package-lock.json', 'web/yarn.lock', 'pnpm-lock.yaml', 'Cargo.lock',
        'public/app.min.js', 'public/app.js.map', 'tsconfig.tsbuildinfo'])
        assert.equal(isNoisePath(p), true, p);
    for (const p of ['package.json', 'src/index.ts', 'src/generated.ts', 'src/lib/generated/helpers.ts'])
        assert.equal(isExcludedPath(p), false, p);
});

test('pasta "generated" isolada continua sendo código normal', () => {
    assert.equal(isExcludedPath('src/generated/routes.ts'), false);
});

test('conteúdo marcado como gerado ou minificado é detectado', () => {
    assert.equal(looksGeneratedContent('a.go', '// Code generated by protoc-gen-go. DO NOT EDIT.\npackage x'), true);
    assert.equal(looksGeneratedContent('a.ts', '/* @generated */\nexport const x = 1;'), true);
    assert.equal(looksGeneratedContent('a.ts', 'export const x = 1;\n'), false);
    assert.equal(looksGeneratedContent('bundle.js', 'a=1;'.repeat(5000)), true);
    const normal = Array.from({ length: 500 }, (_, i) => `const v${i} = ${i};`).join('\n');
    assert.equal(looksGeneratedContent('ok.js', normal), false);
});

test('extraExcludedDirs: nome simples vale em qualquer nível, com barra só a partir da raiz', () => {
    setExtraExcludedDirs(['fixtures', 'apps/web/public/']);
    assert.equal(isExcludedPath('test/fixtures/a.json'), true);
    assert.equal(isExcludedPath('apps/web/public/logo.svg'), true);
    assert.equal(isExcludedPath('other/apps/web/public/logo.svg'), false);
    assert.equal(isExcludedPath('src/index.ts'), false);
    setExtraExcludedDirs([]);
    assert.equal(isExcludedPath('test/fixtures/a.json'), false);
});

test('escrita pelo chat NÃO foi afetada: lockfile na raiz continua editável', () => {
    const { isExcludedPathForWrite } = require('../out/pathRules');
    assert.equal(isExcludedPathForWrite('package-lock.json'), false);
    assert.equal(isExcludedPathForWrite('src/generated/prisma/x.ts'), false);
});
